"use client";
import Link from "next/link";
import { useMemo, useState } from "react";
import { generateStore } from "@/lib/ai";
import type { Category } from "@/lib/types";
import { Chip, LinkButton } from "@/components/ui";
import { ProductArt } from "@/components/ProductArt";

const EXAMPLES: { prompt: string; category: Category }[] = [
  { prompt: "Earthy homeware shop with hand-thrown ceramics, linen and beeswax candles", category: "homeware" },
  { prompt: "Moody dark candle and home fragrance studio with an elegant serif look", category: "homeware" },
  { prompt: "Minimal skincare brand with a three-step routine and soft pink accents", category: "skincare" },
  { prompt: "Clean teal skincare lab focused on barrier repair and sun protection", category: "skincare" },
  { prompt: "Streetwear label making heavyweight basics in black and grey", category: "clothing" },
  { prompt: "Navy workwear brand with canvas trousers and merino knits", category: "clothing" },
  { prompt: "Cosy small-batch coffee roaster with subscriptions and a warm brown palette", category: "coffee" },
  { prompt: "Green specialty tea and pour-over coffee shop with a modern feel", category: "coffee" },
  { prompt: "Dainty gold everyday jewellery, elegant and timeless", category: "jewelry" },
  { prompt: "Purple, vintage-inspired silver rings and pearl earrings", category: "jewelry" },
  { prompt: "Playful orange dog accessories built to survive serious chewers", category: "pet" },
  { prompt: "Blue modern cat and dog bed brand for city apartments", category: "pet" },
];

const FILTERS: { label: string; value: Category | "all" }[] = [
  { label: "All", value: "all" },
  { label: "Home", value: "homeware" },
  { label: "Beauty", value: "skincare" },
  { label: "Apparel", value: "clothing" },
  { label: "Food & Drink", value: "coffee" },
  { label: "Jewellery", value: "jewelry" },
  { label: "Pet", value: "pet" },
  { label: "Sports", value: "general" },
];

export default function ExamplesPage() {
  const [filter, setFilter] = useState<Category | "all">("all");
  const stores = useMemo(() => EXAMPLES.map((e) => ({ ...e, store: generateStore(e.prompt, e.category) })), []);
  const shown = stores.filter((s) => filter === "all" || s.category === filter);

  return (
    <div className="mx-auto max-w-6xl px-4 py-20 sm:px-6">
      <div className="text-center">
        <h1 className="font-display text-5xl">Stores made from a single sentence</h1>
        <p className="mx-auto mt-4 max-w-xl text-muted">{EXAMPLES.length} examples generated by this demo&apos;s engine. Every card shows the brief that produced it — reuse any of them.</p>
        <LinkButton href="/create" className="mt-6">Start your store</LinkButton>
      </div>

      <div className="mt-12 flex flex-wrap justify-center gap-2" role="group" aria-label="Filter by category">
        {FILTERS.map((f) => (
          <Chip key={f.label} selected={filter === f.value} onClick={() => setFilter(f.value)}>{f.label}</Chip>
        ))}
      </div>

      {shown.length === 0 ? (
        <p className="mt-16 text-center text-muted">No examples in this category yet — try describing one yourself.</p>
      ) : (
        <div className="mt-10 grid gap-6 sm:grid-cols-2 lg:grid-cols-3">
          {shown.map(({ prompt, store: s }) => (
            <article key={prompt} className="overflow-hidden rounded-xl border border-border bg-bg shadow-card">
              <div className="p-4" style={{ background: s.palette.bg, color: s.palette.text }}>
                <div className="flex items-center justify-between text-xs">
                  <span className={s.font === "serif" ? "font-serif text-base" : "text-sm font-semibold"}>{s.name}</span>
                  <span className="opacity-60">Shop · Cart</span>
                </div>
                <div className={`mt-4 text-lg leading-tight ${s.font === "serif" ? "font-serif" : "font-semibold"}`}>{s.heroHeadline}</div>
                <div className="mt-3 grid grid-cols-3 gap-2">
                  {s.products.slice(0, 3).map((p) => (
                    <ProductArt key={p.id} seed={p.art} title={p.title} category={s.category} accent={s.palette.accent} soft={s.palette.soft} className="aspect-square w-full rounded" />
                  ))}
                </div>
                <div className="mt-3 h-6 w-24 rounded" style={{ background: s.palette.accent }} aria-hidden />
              </div>
              <div className="border-t border-border p-4">
                <div className="flex items-center justify-between">
                  <h2 className="font-semibold">{s.name}</h2>
                  <span className="rounded-full bg-surface px-2 py-0.5 text-xs capitalize text-muted">{s.category === "general" ? "sports" : s.category}</span>
                </div>
                <p className="mt-2 line-clamp-2 text-sm text-muted">&ldquo;{prompt}&rdquo;</p>
                <Link href={`/create?${new URLSearchParams({ prompt, category: s.category })}`} className="mt-3 inline-block text-sm font-medium text-accent hover:underline">
                  Use this brief →
                </Link>
              </div>
            </article>
          ))}
        </div>
      )}

      <div className="mt-20 grid gap-6 md:grid-cols-2">
        <div className="rounded-xl border border-border bg-surface p-8">
          <h2 className="font-display text-2xl">Already selling somewhere else?</h2>
          <p className="mt-2 text-sm text-muted">Bring your products, customers and orders across. (Migration isn&apos;t part of this demo yet.)</p>
          <LinkButton href="/faq#migration" variant="secondary" className="mt-5">How moving works</LinkButton>
        </div>
        <div className="rounded-xl bg-ink p-8 text-on-ink">
          <h2 className="font-display text-2xl">Your idea is next</h2>
          <p className="mt-2 text-sm text-on-ink/70">One sentence, about a minute, and you&apos;re looking at your store.</p>
          <div className="mt-5 flex gap-3">
            <LinkButton href="/create" variant="accent">Start your store</LinkButton>
            <LinkButton href="/about" variant="ghost" className="text-on-ink hover:bg-white/10">See how it works</LinkButton>
          </div>
        </div>
      </div>
    </div>
  );
}
